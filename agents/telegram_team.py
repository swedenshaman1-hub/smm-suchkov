def _is_transient_gemini_error(exc: Exception) -> bool:
    """Return True for provider/network failures safe to retry on Flash."""
    message = str(exc).lower()
    return any(
        marker in message
        for marker in (
            "429",
            "500",
            "502",
            "503",
            "504",
            "unavailable",
            "overloaded",
            "high demand",
            "timed out",
            "timeout",
            "connection reset",
            "server disconnected",
        )
    )


def _reasoning_call(
    api_key: str,
    primary_model: str,
    system: str,
    user_msg: str,
    *,
    max_tokens: int,
    temperature: float,
) -> str:
    """Use Pro reasoning with a transparent Flash failover.

    ``gemini_call`` already retries transient failures five times. If Pro is
    still unavailable after those retries, repeating the Telegram command is
    pointless, so continue the same stage on Flash with the exact same inputs.
    """
    try:
        return gemini_call(
            api_key,
            primary_model,
            system,
            user_msg,
            max_tokens=max_tokens,
            temperature=temperature,
            disable_thinking=False,
        )
    except Exception as exc:
        empty_response = (
            isinstance(exc, ValueError)
            and "пустой ответ" in str(exc).lower()
        )
        if primary_model == MODEL or not (
            empty_response or _is_transient_gemini_error(exc)
        ):
            raise
        return gemini_call(
            api_key,
            MODEL,
            system,
            user_msg,
            max_tokens=max(5200, max_tokens),
            temperature=temperature,
            disable_thinking=False,
        )


def _notebook_context(role: str, live_context: str = "") -> str:
    """Use live Notebook guidance, with a strictly opt-in static fallback."""
    if live_context.strip():
        return (
            "\n\n═══ ЖИВОЙ ОТВЕТ GEMINI NOTEBOOK ДЛЯ ЭТОЙ ТЕМЫ ═══\n"
            + live_context.strip()
            + "\n═══ КОНЕЦ ЖИВОГО ОТВЕТА ═══\n"
        )
    if os.environ.get("NOTEBOOK_FALLBACK_ENABLED", "0") == "1":
        return notebook_playbooks.context_for(role)
    return ""


def _epistemic_guard(topic: str) -> str:
    """Add a shared reasoning contract for ambiguous causal questions."""
    if not re.search(
        r"\b(?:почему|из-за чего|означает ли|значит ли|доказывает ли)\b",
        (topic or "").lower(),
    ):
        return ""
    return """

═══ ПРОТОКОЛ НЕОДНОЗНАЧНОЙ ПРИЧИННОЙ ТЕМЫ ═══
Тема спрашивает о причине или о значении наблюдения. Если исследовательская
записка не содержит отдельного проверяемого источника, запрещено выбирать одну
скрытую психологическую причину и выдавать её за ответ.

Обязательная логика:
1. Назови наблюдение, которое действительно дано в теме.
2. Прямо отдели его от вывода: само наблюдение ещё не доказывает одну трактовку.
3. Не объясняй его мозгом, телом, психикой, защитным механизмом, привычным
   паттерном, страхом, репутацией или потребностью без источника.
4. Вместо меню домыслов дай два или три проверяемых признака или вопроса,
   которые помогают различить варианты в конкретной ситуации.
5. Если тема спрашивает «означает ли это», ответ должен явно сказать:
   «не обязательно», «не всегда» или «само по себе это не доказывает».
═══ КОНЕЦ ПРОТОКОЛА ═══
"""

