def _restore_required_russian_hyphens(text: str) -> str:
    """Restore common mandatory hyphens after decorative dash cleanup."""
    indefinite_stems = (
        r"кто|кого|кому|кем|ком|что|чего|чему|чем|чём|"
        r"какой|какого|какому|каким|каком|какая|какую|какое|"
        r"какие|каких|какими|чей|чьего|чьему|чьим|чья|чьей|"
        r"чью|чьё|чьи|чьих|чьими|где|куда|откуда|когда|как|"
        r"сколько|почему|зачем"
    )
    text = re.sub(
        rf"\b({indefinite_stems})\s+(то|либо|нибудь)\b",
        r"\1-\2",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        rf"\b(кое)\s+({indefinite_stems})\b",
        r"\1-\2",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        r"\b(по)\s+(прежнему|настоящему|другому|своему|новому|старому|"
        r"человечески|русски|английски|мужски|женски|особенному)\b",
        r"\1-\2",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        r"\b(из)\s+(за|под)\b",
        r"\1-\2",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        r"\b(во)\s+(первых|вторых|третьих|четвёртых|четвертых|пятых)\b",
        r"\1-\2",
        text,
        flags=re.IGNORECASE,
    )
    repeated_forms = {
        r"\bвот\s+вот\b": "вот-вот",
        r"\bеле\s+еле\b": "еле-еле",
        r"\bчуть\s+чуть\b": "чуть-чуть",
        r"\bдавным\s+давно\b": "давным-давно",
        r"\bмало\s+помалу\b": "мало-помалу",
        r"\bточь\s+в\s+точь\b": "точь-в-точь",
    }
    for pattern, replacement in repeated_forms.items():
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    return text


def clean_human_surface(topic: str, text: str) -> str:
    """Apply Dmitry's final human-surface rules deterministically."""
    clean = clean_editorial_output(text)
    clean = re.sub(
        r"^\s*(?:#{1,6}\s*|\*{1,2})?(?:тема|заголовок)\s*:\s*",
        "",
        clean,
        flags=re.IGNORECASE,
    )
    normalized_topic = (topic or "").strip()
    if normalized_topic and clean.casefold().startswith(normalized_topic.casefold()):
        clean = clean[len(normalized_topic):].lstrip(" \t\r\n:;,.!?—–-")

    # Remove quotation glyphs and Markdown emphasis requested by the author.
    clean = clean.translate(
        str.maketrans({
            "«": "", "»": "", "“": "", "”": "", "„": "", '"': "",
            "‹": "", "›": "", "‘": "", "’": "", "'": "",
        })
    )
    clean = clean.replace("**", "").replace("__", "")

    head_forms = {
        "башка": "голова",
        "башки": "головы",
        "башке": "голове",
        "башку": "голову",
        "башкой": "головой",
        "башкою": "головою",
        "бошка": "голова",
        "бошки": "головы",
        "бошке": "голове",
        "бошку": "голову",
        "бошкой": "головой",
        "бошкою": "головою",
    }

    def replace_head_word(match: re.Match) -> str:
        original = match.group(0)
        replacement = head_forms[original.casefold()]
        return replacement.capitalize() if original[:1].isupper() else replacement

    clean = re.sub(
        r"\b(?:башк[аиу]|башк(?:е|ой|ою)|бошк[аиу]|бошк(?:е|ой|ою))\b",
        replace_head_word,
        clean,
        flags=re.IGNORECASE,
    )

    # Remove visual/decorative dashes first. Mandatory spelling hyphens are
    # restored below, otherwise "что-то" and "по-прежнему" become errors.
    clean = re.sub(r"[‐‑‒–—−-]", " ", clean)
    clean = re.sub(r"([!?])\.", r"\1", clean)
    clean = re.sub(r"\s*,\s*,+\s*", ", ", clean)
    clean = re.sub(r"[ \t]+([,.;:!?])", r"\1", clean)
    clean = re.sub(r"[ \t]{2,}", " ", clean)
    clean = re.sub(r"\n[ \t]+", "\n", clean)
    clean = re.sub(r"\n{3,}", "\n\n", clean)
    clean = _restore_required_russian_hyphens(clean)
    return clean.strip()


def enforce_length(text: str, max_chars: int = 1850) -> str:
    """Last-resort deterministic fit that keeps the opening and conclusion."""
    clean = text.strip()
    if len(clean) <= max_chars:
        return clean
    sentences = re.findall(
        r".+?[.!?…](?:[»\")]+)?(?=\s|$)",
        clean,
        flags=re.DOTALL,
    )
    if len(sentences) >= 2:
        conclusion = sentences[-1].strip()
        budget = max_chars - len(conclusion) - 2
        kept: list[str] = []
        used = 0
        for sentence in sentences[:-1]:
            normalized = " ".join(sentence.split())
            addition = len(normalized) + (1 if kept else 0)
            if used + addition > budget:
                break
            kept.append(normalized)
            used += addition
        candidate = " ".join(kept + [conclusion]).strip()
        if 350 <= len(candidate) <= max_chars:
            return candidate
    prefix = clean[:max_chars]
    boundary = max(
        prefix.rfind("."),
        prefix.rfind("!"),
        prefix.rfind("?"),
        prefix.rfind("…"),
    )
    return prefix[: boundary + 1].strip() if boundary >= 350 else prefix.rstrip() + "…"


