def extract_variant(variants: str, letter: str) -> str:
    """Extract one draft despite Markdown headings or descriptive suffixes.

    Never return all three drafts when recognizable variant headings are present.
    """
    letters = "АБВ"
    letter = letter if letter in letters else "А"
    header = re.compile(
        r"(?:^|\n)\s*(?:#{1,6}\s*)?(?:\*{1,2}|_{1,2})?\s*"
        r"ВАРИАНТ\s+([АБВ])\s*(?:\*{1,2}|_{1,2})?\s*"
        r"(?:(?:[:—-])[^\n]*)?\n",
        re.IGNORECASE,
    )
    matches = list(header.finditer(variants))
    sections = {}
    for index, match in enumerate(matches):
        start = match.end()
        end = matches[index + 1].start() if index + 1 < len(matches) else len(variants)
        sections[match.group(1).upper()] = variants[start:end].strip()
    if sections:
        return sections.get(letter) or next(iter(sections.values()))
    return variants.strip()


def validate_post(text: str) -> list[str]:
    errors = []
    clean = text.strip()
    if len(clean) < 350:
        errors.append("текст короче 350 знаков")
    # The author requested compact Telegram posts; this is a delivery gate.
    if len(clean) > 1900:
        errors.append("текст длиннее 1900 знаков")
    if re.search(r"\bсоматическ\w*\s+терапевт\w*\b|\bсоматотерапевт\w*\b|\bsomatic\s+therapist\b", clean, re.IGNORECASE):
        errors.append("нарушена брендовая граница: позиционирование как соматического терапевта")
    if re.search(r"(?:^|\n)\s*(ВАРИАНТ|РЕШЕНИЕ|КОММЕНТАРИЙ)\b", clean, re.IGNORECASE):
        errors.append("в тексте осталась служебная разметка")
    if clean and clean[-1] not in ".!?…»\")":
        errors.append("последнее предложение выглядит оборванным")
    return errors


def editorial_contract_issues(topic: str, text: str) -> list[str]:
    """Deterministic publication contract for the bounded editorial pipeline."""
    raw = text.strip()
    clean = clean_human_surface(topic, text)
    lowered = clean.lower()
    raw_lowered = raw.lower()
    topic_lower = (topic or "").lower()
    issues: list[str] = []

    if len(clean) < 850:
        issues.append("раскрой мысль до 850–1500 знаков")
    if len(clean) > 1800:
        issues.append("сократи текст до 1500 знаков без нового смыслового круга")

    topic_words = re.findall(r"[а-яё0-9]+", topic_lower)
    text_words = re.findall(r"[а-яё0-9]+", raw_lowered)
    prefix_size = min(8, len(topic_words))
    if prefix_size >= 5 and text_words[:prefix_size] == topic_words[:prefix_size]:
        issues.append("не копируй исходную тему в качестве хука")
    opening = " ".join(clean.split())[:240].lower()
    if re.match(r"^в\s+какой\s+момент\b.{0,150}\bпревраща\w*", opening):
        issues.append(
            "замени шаблонный хук «В какой момент X превращается в Y?» "
            "на точное наблюдение или противоречие"
        )

    if "сильнее" in topic_lower and not re.search(
        r"\bсильнее\b|\bпуга\w*\s+(?:гораздо\s+)?больше\b|"
        r"\bстрах\w*\b.{0,80}\bбольше\b",
        lowered,
        re.DOTALL,
    ):
        issues.append(
            "ответь прямо, почему одно пугает сильнее другого; не описывай "
            "только одну сторону сравнения"
        )

    if re.search(
        r"\b(?:хорошо\s+отлаженн\w*\s+систем\w*|знаком\w*\s+земл\w*\s+под\s+ног\w*|"
        r"шаг\w*\s+в\s+неизвестност\w*|будущ\w*\s+не\s+гарантирован\w*)\b",
        lowered,
    ):
        issues.append("замени готовые метафоры и клише на конкретное человеческое наблюдение")

    has_ty = bool(re.search(r"\b(?:ты|тебя|тебе|тобой|твой|твоя|твоё|твои|твоего|твою)\b", lowered))
    has_vy = bool(re.search(r"\b(?:вы|вас|вам|вами|ваш|ваша|ваше|ваши|вашего|вашу)\b", lowered))
    if has_ty and has_vy:
        issues.append("не смешивай обращения «ты» и «вы»")
    topic_has_gender = bool(re.search(r"\b(?:мужчин|женщин|муж|жена|парень|девушка|он|она)\w*\b", topic_lower))
    if not topic_has_gender and re.search(r"\b(?:он|она|ему|ей|его|её)\b", lowered):
        issues.append(
            "сохрани нейтральный пол персонажа: не переключай общий образ человека на «он» или «она»"
        )
    if has_ty and re.search(r"\b(?:близкий человек|человек|партн[её]р)\b.{0,180}\b(?:он|она|ему|ей|его|её)\b", lowered, re.DOTALL):
        issues.append(
            "не смешивай перспективы наблюдателя «ты» и отдельного персонажа «он/она»"
        )
    if "сильн" not in topic_lower and re.search(r"\b(?:образ|роль)\s+сильн\w*\b", lowered):
        issues.append("не приписывай человеку мотив сохранять образ или роль сильного")
    if re.search(r"\bты\s+(?:думаешь|считаешь|решаешь),?\s+что\b", lowered):
        issues.append("не назначай читателю мысль или объяснение от второго лица")
    if "нужн" not in topic_lower and re.search(r"\bпочувств\w*\s+себя\s+нужн\w*\b", lowered):
        issues.append("не назначай близкому человеку чувство собственной нужности")
    if re.search(
        r"\b(?:любит|выбирает|слышит|понимает)\s+ли\s+он\b|"
        r"\bпартн[её]р\w*\b.{0,160}\b(?:он|его|ему)\b",
        lowered,
        re.DOTALL,
    ):
        issues.append(
            "не назначай партнёру мужской пол, если он не указан в теме"
        )

    second_person = len(re.findall(
        r"\b(?:ты|тебя|тебе|тобой|твой|твоя|твоё|твои|"
        r"вы|вас|вам|вами|ваш|ваша|ваше|ваши)\b",
        lowered,
    ))
    if second_person > 5:
        issues.append("оставь не более пяти явных обращений к читателю")

    if re.search(r"\w+\([а-яё]\)", lowered):
        issues.append("убери машинную гендерную заглушку в скобках")
    if re.search(
        r"\b(?:ты|тебя|тебе|твой|твоя|твоё)\b[^.!?]{0,120}"
        r"\b(?:была|готова|согласилась|решила|отстаивала|подумала|сделала)\b",
        lowered,
    ):
        issues.append(
            "убери женскую форму из обращения к смешанной аудитории"
        )
    if re.search(
        r"\b(?:ты|тебя|тебе|твой|твоя|твоё)\b[^.!?]{0,120}"
        r"\b(?:был|готов|сказал|подумал|решил|согласился|сделал)\b",
        lowered,
    ):
        issues.append(
            "убери мужскую форму из обращения к смешанной аудитории"
        )
    if re.search(r"\bреакци\w*\s*,\s*не\s+\w+ть\b", lowered):
        issues.append(
            "исправь грамматику конструкции «реакция, не сделать»"
        )
    if re.search(r"\bпо\s+разному\b", lowered):
        issues.append("сохрани обязательный дефис в слове «по-разному»")
    if re.search(
        r"\b(?:есть|бывают|существуют)\s+просьб\w*\s+"
        r"(?:инструкци\w*|вопрос\w*)\b",
        lowered,
    ):
        issues.append(
            "исправь грамматику конструкции «просьбы инструкции/вопросы»"
        )
    if re.search(
        r"\bесли\s+ответ\s+(?:первое|второе|третье)\b",
        lowered,
    ):
        issues.append(
            "исправь согласование конструкции «если ответ второе»"
        )
    if re.search(
        r"\b(?:сказал|сказала|спросил|спросила|ответил|ответила)"
        r"\s*:\s*[А-ЯЁ]",
        raw,
    ):
        issues.append(
            "перестрой прямую речь, если кавычки удалены правилами оформления"
        )

    relationship_topic = bool(
        re.search(r"\b(?:отношен|любов|партн[её]р|близост|расставан)\w*", topic_lower)
    )
    commodity_patterns = (
        r"\b(?:книг|украшен|товар|продукт|ценник|магазин)\w*.{0,180}"
        r"\b(?:цен|доступ|выбира|усили|вкладыва)\w*|"
        r"\b(?:цен|доступ|выбира|усили|вкладыва)\w*.{0,180}"
        r"\b(?:книг|украшен|товар|продукт|ценник|магазин)\w*|"
        r"\bсозда\w*.{0,50}\bдефицит\w*|"
        r"\b(?:слишком|всегда)\s+доступн\w*.{0,100}\b(?:цен|выбира)\w*|"
        r"\bзастав\w*.{0,80}\bвкладыва\w*"
    )
    if relationship_topic and re.search(commodity_patterns, lowered, re.DOTALL):
        issues.append(
            "не объясняй человеческую ценность товаром, дефицитом или усилием выбора"
        )

    forbidden_surface = {
        "убери формулу «на самом деле»": r"\bна\s+самом\s+деле\b",
        "убери формулу «вернуться/вернуть внимание к себе»": r"\bверн\w*.{0,45}\b(?:к\s+себе|внимани\w*\s+к\s+себе)\b",
        "убери штамп «новые горизонты»": r"\bнов\w*\s+горизонт\w*\b",
        "убери штамп «внутри бушует буря»": r"\bвнутри\b.{0,35}\bбур[яеи]\b",
        "не предлагай почувствовать тело": r"\bпочувств\w*.{0,25}\bтел\w*\b",
        "не предлагай глубокий вдох как универсальное решение": r"\bглубок\w*\s+вдох\w*\b",
    }
    for message, pattern in forbidden_surface.items():
        if re.search(pattern, lowered, re.DOTALL):
            issues.append(message)

    sentences = [
        part.strip()
        for part in re.split(r"(?<=[.!?…])\s+", clean)
        if part.strip()
    ]
    if sentences and re.match(
        r"^(?:чтобы|потому\s+что|хотя|если|когда|пока|поскольку|так\s+как)\b",
        sentences[-1].lower(),
    ):
        issues.append("заверши финальную мысль главным, а не придаточным предложением")
    final_text = " ".join(sentences[-2:]).lower() if sentences else lowered[-320:]
    literal_door_topic = bool(re.search(r"\bдвер\w*\b", topic_lower))
    if not literal_door_topic and re.search(
        r"\b(?:двер\w*\s+(?:к|в)\s+\w+|двер\w*\s+(?:открыт|закрыт|заперт)\w*|"
        r"(?:открыт|закрыт|запер)\w*\s+двер\w*)\b",
        final_text,
    ):
        issues.append(
            "замени шаблонную метафору двери в финале на прямое человеческое различение"
        )
    paragraph_count = len([
        part for part in re.split(r"\n\s*\n", clean) if part.strip()
    ])
    if paragraph_count > 9:
        issues.append("собери текст в 6–9 содержательных абзацев")

    issues.extend(validate_post(clean))
    issues.extend(quality_warnings(clean))
    issues.extend(structural_warnings(topic, clean))
    return list(dict.fromkeys(issues))


