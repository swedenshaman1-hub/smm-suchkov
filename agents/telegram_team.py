def _finalize_blueprint(blueprint: str, topic: str = "") -> str:
    """Inject the exact topic invariant and one immutable program guard."""
    clean = re.split(
        r"(?im)^ЗАПРЕЩЕНО В ТЕКСТЕ:",
        blueprint.strip(),
        maxsplit=1,
    )[0].rstrip()
    topic_line = " ".join((topic or "").split())
    if topic_line:
        invariant = f"НЕИЗМЕНЯЕМЫЙ ФАКТ ТЕМЫ: {topic_line}"
        fact_contract = (
            "ФАКТИЧЕСКИЙ КОНТРАКТ: разрешено утверждать только то, что прямо "
            "дано в неизменяемом факте темы или имеет явную проверяемую опору. "
            "Один вымышленный художественный пример разрешён как иллюстрация, "
            "но его нельзя выдавать за реального клиента, случай Дмитрия, "
            "исследование или доказательство общего закона."
        )
        if re.search(r"(?im)^НЕИЗМЕНЯЕМЫЙ ФАКТ ТЕМЫ:.*$", clean):
            clean = re.sub(
                r"(?im)^НЕИЗМЕНЯЕМЫЙ ФАКТ ТЕМЫ:.*$",
                invariant,
                clean,
                count=1,
            )
        else:
            clean = re.sub(
                r"(?im)^(КАРКАС:\s*ГОТОВ)\s*$",
                rf"\1\n{invariant}",
                clean,
                count=1,
            )
        if re.search(r"(?im)^ФАКТИЧЕСКИЙ КОНТРАКТ:.*$", clean):
            clean = re.sub(
                r"(?im)^ФАКТИЧЕСКИЙ КОНТРАКТ:.*$",
                fact_contract,
                clean,
                count=1,
            )
        else:
            clean = re.sub(
                r"(?im)^(НЕИЗМЕНЯЕМЫЙ ФАКТ ТЕМЫ:.*)$",
                rf"\1\n{fact_contract}",
                clean,
                count=1,
            )
    clean = re.sub(
        r"(?im)^-\s*этическая граница:.*$",
        "- этическая граница: не приписывать партнёру мотивы и отделять "
        "наблюдаемое от вывода",
        clean,
    )
    return f"{clean}\n{BLUEPRINT_GUARDRAILS}"


def audit_blueprint_fidelity(
    topic: str,
    blueprint: str,
    api_key: str,
) -> list[str]:
    """Semantically reject topic drift and invented claims before writing."""
    user_msg = (
        f"ИСХОДНАЯ ТЕМА:\n{topic}\n\n"
        f"ПРОВЕРЯЕМЫЙ BLUEPRINT:\n{blueprint}"
    )
    review = _reasoning_call(
        api_key,
        MODEL,
        BLUEPRINT_FIDELITY_AUDIT_PROMPT + BRAND_BOUNDARY,
        user_msg,
        max_tokens=2800,
        temperature=0.0,
    ).strip()
    lines = [line.strip() for line in review.splitlines() if line.strip()]
    first = lines[0].upper() if lines else ""
    if "КАРКАС: ПРИНЯТ" in first:
        return []
    details = [
        re.sub(r"^[\s•*\-\d.)]+", "", line).strip()
        for line in lines[1:5]
    ]
    details = [detail for detail in details if detail]
    if not details:
        details = ["семантический аудит не подтвердил фактическую верность каркаса"]
    return [f"семантический аудит: {detail}" for detail in details]


