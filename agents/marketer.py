def run(topic: str, analyst_output: str, strategy_output: str, api_key: str,
        final_content: str = None) -> dict:
    memory = memory_utils.load(AGENT_ID)
    system = SYSTEM_PROMPT + memory_utils.build_context(memory, topic)

    user_msg = f"""Тема контента: «{topic}»

ТЗ АРТЁМА (стратегический угол, посыл, анти-язык, температура аудитории):
{strategy_output}

АНАЛИЗ ЦА от Нины (боли, триггеры):
{analyst_output}"""

    if final_content:
        user_msg += f"""

ФИНАЛЬНЫЙ КОНТЕНТ (от Даши, готов к публикации — оценивай именно его):
{final_content}

Дай маркетинговую оценку по 5 разделам: виральный потенциал, коммерческий потенциал, позиционирование Дмитрия, рекомендации, итоговая оценка."""
    else:
        user_msg += """

Финальный текст ещё не готов — оцени стратегический потенциал темы и ТЗ по 5 разделам.
Фиксируй явно: «предварительная оценка, финального текста нет»."""

    result_text = gemini_call(api_key, MODEL, system, user_msg, max_tokens=6000, temperature=0.7)

    reflection_text = gemini_call(
        api_key, MODEL, system,
        f"Ты проанализировал тему «{topic}». Выдели 1-2 маркетинговых урока для запоминания.\nФормат: каждый с '•'",
        max_tokens=300, temperature=0.5
    )
    for line in reflection_text.strip().split("\n"):
        if line.strip() and "•" in line:
            memory_utils.add_insight(memory, line.strip().lstrip("•").strip(), topic, "marketing")

    memory_utils.add_topic(memory, topic, result_text[:300])
    memory_utils.save(AGENT_ID, memory)

    return {"agent": "Олег (Маркетолог)", "topic": topic, "marketing": result_text}
