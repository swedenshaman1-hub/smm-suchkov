def run(topic: str, analyst_output: str, strategy_output: str, marketing_output: str,
        api_key: str, editor_feedback: str = None, iteration: int = 1) -> dict:
    memory = memory_utils.load(AGENT_ID)
    system = SYSTEM_PROMPT + memory_utils.build_context(memory, topic)

    user_msg = f"""Тема: «{topic}»

ТЗ ОТ АРТЁМА ВОЛКОВА (работай строго по нему):
{strategy_output}

ТЕЛЕСНЫЙ СЛЕД И ЯЗЫК КЛИЕНТА от Нины (используй напрямую):
{analyst_output}"""

    if marketing_output:
        user_msg += f"""

МАРКЕТИНГОВЫЕ РЕКОМЕНДАЦИИ ОЛЕГА (учти при написании):
{marketing_output}"""

    user_msg += """

Напиши полный Instagram-пакет:
1. ОСНОВНОЙ ПОСТ (500–900 символов, первая строка до «ещё» — крючок)
2. СТОРИС-ПРОГРЕВ (10–12 сторис, логика нарастания по структуре)
3. КАРУСЕЛЬ (8 слайдов, каждый — один удар, структура строго по промту)
4. REELS (сценарий с разбивкой по секундам: [0–3 сек] / [3–15 сек] / [15–35 сек] / [35–60 сек])

После пакета — самопроверка связности по 6 пунктам."""

    if editor_feedback:
        user_msg += f"\n\nИТЕРАЦИЯ {iteration}. ЛЕНА ВЕРНУЛА С ЗАМЕЧАНИЯМИ:\n{editor_feedback}\nПерепиши с учётом всех замечаний."

    result_text = gemini_call(api_key, MODEL, system, user_msg, max_tokens=9000, temperature=0.8)

    if not editor_feedback:
        reflection_text = gemini_call(
            api_key, MODEL, system,
            f"Ты написала Instagram-пакет для «{topic}». Выдели 1-2 приёма для запоминания.\nФормат: каждый с '•'",
            max_tokens=300, temperature=0.5
        )
        for line in reflection_text.strip().split("\n"):
            if line.strip() and "•" in line:
                memory_utils.add_insight(memory, line.strip().lstrip("•").strip(), topic, "instagram")

    memory_utils.add_topic(memory, topic, f"IG итерация {iteration}")
    memory_utils.save(AGENT_ID, memory)

    return {"agent": "Катя (Instagram)", "topic": topic, "iteration": iteration, "texts": result_text}
