def run(topic: str, analyst_output: str, api_key: str, feedback: str = None) -> dict:
    memory = memory_utils.load(AGENT_ID)
    system = SYSTEM_PROMPT + memory_utils.build_context(memory, topic)

    user_msg = f"""Тема: «{topic}»

АНАЛИЗ ЦА от Нины Соколовой:
{analyst_output}

Разработай полную стратегию по всем 16 пунктам структуры.
Начни с реального рассмотрения минимум 4 альтернативных углов (п.1) — не бери первый яркий вариант.
В тесте на ложную простоту приведи минимум ДВА реальных контрпримера к своему тезису — не риторический вопрос с ответом «нет».
Если тема связана с реакцией/состоянием героя в связи с другим человеком — обязательно пройди блок «Причинная цепочка» и «Тест переноса вины» до выбора угла, не после.
Метафора необязательна (п.9) — реши осознанно, не автоматически.
Финальный блок решений (п.15) обязателен целиком, включая схему одним предложением."""
    if feedback:
        user_msg += f"""

ОБРАТНАЯ СВЯЗЬ (редактор отменил предыдущую стратегию):
{feedback}

Это пересмотр после отклонения, не косметическая правка. Пройди Шаг 1–3 (п.1) заново, с нуля — не патчи старый угол.
В Шаге 2 (оценка углов) ты сам выставляешь вердикты «сильный/рабочий/слабый/отклонить» — если какому-то углу ты сам поставил «риск повтора» или подобную оговорку, ты не имеешь права выбрать его в Шаге 3, даже если формально он «рабочий». Выбирай только угол без такой оговорки от тебя самого.
Также заново сверься со списком ЗАПРЕЩЁННЫХ АРХИТЕКТУР/ОБРАЗОВ/СХЕМ команды (если он передан в начале этого промпта) — он мог обновиться с прошлой попытки."""

    result_text = gemini_call(api_key, MODEL, system, user_msg, max_tokens=9000, temperature=0.7)

    reflection_text = gemini_call(
        api_key, MODEL, system,
        f"Ты разработал стратегию для «{topic}». Выдели 1-2 ключевых решения для запоминания.\nФормат: каждое с '•'",
        max_tokens=300, temperature=0.5
    )
    for line in reflection_text.strip().split("\n"):
        if line.strip() and "•" in line:
            memory_utils.add_insight(memory, line.strip().lstrip("•").strip(), topic, "strategy")

    angle_match = re.search(r"ВЫБРАННЫЙ УГОЛ\s*:?\**\s*(.+)", result_text)
    hook_match = re.search(r"ЭМОЦИОНАЛЬНЫЙ КРЮЧОК\s*\n+(.+)", result_text)
    image_match = re.search(r"ГЛАВНЫЙ ОБРАЗ[^:]*:\**\s*(.+)", result_text)
    scheme_match = re.search(r"СХЕМА ОДНИМ ПРЕДЛОЖЕНИЕМ[^:]*:\**\s*(.+)", result_text)

    angle = angle_match.group(1).strip()[:150] if angle_match else ""
    hook = hook_match.group(1).strip()[:150] if hook_match else ""
    central_image = image_match.group(1).strip(" *").strip()[:60] if image_match else ""
    scheme = scheme_match.group(1).strip(" *").strip()[:150] if scheme_match else ""

    memory_utils.add_topic(memory, topic, f"Угол: {angle} | Крючок: {hook}")
    if central_image and not central_image.lower().startswith(("нет", "не нужна", "не нужен")):
        memory_utils.add_used_image(central_image, topic)
    if scheme:
        memory_utils.add_used_scheme(scheme, topic)
    memory_utils.save(AGENT_ID, memory)

    return {"agent": "Стратег", "topic": topic, "strategy": result_text}
