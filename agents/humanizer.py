def find_denylisted(text: str) -> list:
    """Промптовый запрет не гарантирует, что модель не скажет забаненную фразу — это
    вероятностное снижение, не фильтр. Эта проверка — детерминированная сетка безопасности
    после Даши, а не замена денилиста в промпте."""
    t = text.lower()
    return [p for p in DENYLIST_PHRASES if p in t]


