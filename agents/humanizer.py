DENYLIST_PHRASES = [
    "солнечное сплетение", "ватные ноги", "озноб в груди", "телесные зажимы", "зажимы",
    "тяжёлые плечи", "сжатые челюсти", "превращаешься в зомби", "зомби с набором задач",
    "мышечный спазм", "разжать", "внутренний судья", "внутренний тюремщик", "внутренний надзиратель",
    "внутренний прокурор", "ты сам себе тюрьма", "соматотерапевт", "деконструкция",
]

# "Тело как система тревоги" — отдельная семья приёмов, где тело в любой форме "сообщает"
# читателю что-то (кричит/сигналит/взывает/достучаться/докричаться/требует внимания) или
# называется "самым честным свидетелем/проводником". Ловим по корню слова через regex, а не
# списком конкретных словоформ — на практике модель трижды обходила литеральный список,
# просто меняя окончание или синоним ("сигнализирует" → "сигналит", "проводник" → "свидетель"),
# так что список фиксированных строк для этого приёма бесполезен в принципе.
TELO_ALARM_PATTERNS = [
    re.compile(r"\bтел[оа]\b(?:\s+\S+){0,4}?\s+(достуч\w*|докрич\w*|крич\w*|взыва\w*|сигнал\w*)", re.IGNORECASE),
    re.compile(r"\bтел[оа]\b(?:\s+\S+){0,4}?\s+требует\s+внимани\w*", re.IGNORECASE),
    re.compile(r"сам\w+\s+честн\w+\s+(свидетел\w*|проводник\w*)", re.IGNORECASE),
    # Конкатенированные хэштеги (#телосигналит) не имеют пробела между "тело" и глаголом —
    # предыдущие три паттерна их не ловят в принципе, нужен отдельный шаблон без границы слова
    re.compile(r"#тело(сигнал\w*|кричит\w*|взыва\w*|достуч\w*|докрич\w*)", re.IGNORECASE),
]


def find_denylisted(text: str) -> list:
    """Промптовый запрет не гарантирует, что модель не скажет забаненную фразу — это
    вероятностное снижение, не фильтр. Эта проверка — детерминированная сетка безопасности
    после Даши, а не замена денилиста в промпте."""
    t = text.lower()
    found = [p for p in DENYLIST_PHRASES if p in t]
    for pattern in TELO_ALARM_PATTERNS:
        for m in pattern.finditer(text):
            snippet = m.group(0).strip()
            if snippet.lower() not in (f.lower() for f in found):
                found.append(snippet)
    return found


