def run(topic: str, analyst_output: str, strategy_output: str,
        copywriter_output: str, api_key: str, iteration: int = 1) -> dict:
    memory = memory_utils.load(AGENT_ID)
    system = SYSTEM_PROMPT + memory_utils.build_context(memory, topic)

    user_msg = f"""Тема: «{topic}»

ТЗ ОТ АРТЁМА ВОЛКОВА (работай строго по нему):
{strategy_output}

АНАЛИЗ ЦА от Нины (контекст):
{analyst_output}

ДВА ВАРИАНТА TELEGRAM-ПОСТА от Маши (итерация {iteration}):
{copywriter_output}

Сначала пройди блок «СНАЧАЛА СТРАТЕГИЯ» — если стратегия не проходит эту проверку, зафиксируй это явно и не трать разбор на построчную правку текста, который всё равно нужно менять на уровне угла. Только если стратегия проходит — переходи к чеклисту по каждому варианту (стратегия, платформа, авторский голос, тест живого человека). Сравни варианты. Вынеси ВЕРДИКТ по каждому и ОБЩИЙ ВЕРДИКТ.

ПЕРВОЙ строкой ответа, до начала разбора, укажи: «РЕКОМЕНДУЕМЫЙ ВАРИАНТ: А» или «РЕКОМЕНДУЕМЫЙ ВАРИАНТ: Б» (или «РЕКОМЕНДУЕМЫЙ ВАРИАНТ: НИ ОДИН — проблема в стратегии» если блок «сначала стратегия» не пройден) — с однострочным обоснованием. Это обязательно должно быть первой строкой, а не выводом в конце: если разбор обрежется по длине, решение всё равно должно быть зафиксировано."""

    result_text = gemini_call(api_key, MODEL, system, user_msg, max_tokens=8000, temperature=0.6,
                               disable_thinking=True)

    # Модель не всегда пишет вердикт на той же строке, что заголовок "ОБЩИЙ ВЕРДИКТ" —
    # часто заголовок и текст вердикта разделены пустой строкой. Старая построчная проверка
    # в этом случае брала пустую строку-заголовок и считала это отклонением по умолчанию.
    verdict_match = re.search(r"общий вердикт[:\s]*\n*(.{0,200})", result_text, re.IGNORECASE | re.DOTALL)
    verdict_text = verdict_match.group(1).lower() if verdict_match else ""
    accepted = "требуют доработки" not in verdict_text and "отклонены" not in verdict_text and (
        "готовы к очеловечиванию" in verdict_text or "один вариант готов" in verdict_text
    )

    if not accepted:
        reflection_text = gemini_call(
            api_key, MODEL, system,
            f"Ты отклонил тексты по теме «{topic}». Выдели 1-2 типичных ошибки для памяти.\nФормат: каждая с '•'",
            max_tokens=300, temperature=0.5
        )
        for line in reflection_text.strip().split("\n"):
            if line.strip() and "•" in line:
                memory_utils.add_technique(memory, line.strip().lstrip("•").strip(), topic, successful=False)
    else:
        memory_utils.add_technique(memory, f"Принят с первого раза: {topic[:50]}", topic, successful=True)

    memory_utils.add_topic(memory, topic, f"Итерация {iteration}, принято: {accepted}")
    memory_utils.save(AGENT_ID, memory)

    chosen_variant = None
    match = re.search(r"РЕКОМЕНДУЕМЫЙ ВАРИАНТ\s*:?\s*([АБ])\b", result_text, re.IGNORECASE)
    if match:
        chosen_variant = match.group(1).upper()

    strategy_rejected = bool(re.search(r"РЕКОМЕНДУЕМЫЙ ВАРИАНТ\s*:?\s*НИ\s*ОДИН", result_text, re.IGNORECASE))

    return {
        "agent": "Редактор", "topic": topic, "iteration": iteration, "accepted": accepted,
        "review": result_text, "chosen_variant": chosen_variant, "strategy_rejected": strategy_rejected,
    }


def quick_check(topic: str, strategy_output: str, text: str, api_key: str) -> dict:
    """Проверка ОДНОГО текста после тональной переработки Даши — не полный run()
    с сравнением двух вариантов (там сравнивать нечего, текст один и тот же до и
    после), а быстрая проверка по пяти обязательным вопросам и критерию готовности."""
    memory = memory_utils.load(AGENT_ID)
    system = SYSTEM_PROMPT + memory_utils.build_context(memory, topic)

    user_msg = f"""Тема: «{topic}»

ТЗ АРТЁМА (для контекста стратегии и анти-языка):
{strategy_output}

ТЕКСТ ПОСЛЕ ТОНАЛЬНОЙ ПЕРЕРАБОТКИ ДАШИ (стратегия и структура уже были одобрены раньше, сейчас проверяешь только что не сломалось после смены тона):
{text}

Ответь на пять обязательных вопросов из раздела «ПЕРЕД ОДОБРЕНИЕМ» и на критерий готовности. Проверь анти-язык из ТЗ и «тело как система тревоги» отдельно.
ПЕРВОЙ строкой укажи «РЕШЕНИЕ: ОДОБРЕНО» или «РЕШЕНИЕ: ТРЕБУЕТ ПРАВКИ» с однострочным обоснованием."""

    result_text = gemini_call(api_key, MODEL, system, user_msg, max_tokens=3000, temperature=0.5,
                               disable_thinking=True)

    first_line = result_text.strip().split("\n", 1)[0].upper()
    accepted = "ОДОБРЕНО" in first_line

    return {"agent": "Редактор", "topic": topic, "accepted": accepted, "review": result_text}
