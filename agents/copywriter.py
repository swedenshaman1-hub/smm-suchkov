def run(topic: str, analyst_output: str, strategy_output: str,
        api_key: str, editor_feedback: str = None, iteration: int = 1) -> dict:
    memory = memory_utils.load(AGENT_ID)
    system = SYSTEM_PROMPT + memory_utils.build_context(memory, topic)

    user_msg = f"""Тема: «{topic}»

ТЗ ОТ АРТЁМА ВОЛКОВА (работай строго по нему, включая решения нужна ли метафора/телесность/CTA):
{strategy_output}

ТЕЛЕСНЫЙ СЛЕД И ЯЗЫК КЛИЕНТА от Нины (используй только если ТЗ явно просит телесность):
{analyst_output}

Напиши 2 варианта Telegram-поста, различающихся АРХИТЕКТУРОЙ раскрытия темы.
Перед каждым вариантом — черновой каркас.
После вариантов — блок «ПОЧЕМУ ЭТИ ДВА ВАРИАНТА» и CTA-строки (даже если CTA не используется — укажи это явно)."""

    if editor_feedback:
        user_msg += f"""

ИТЕРАЦИЯ {iteration}. ИГОРЬ ВЕРНУЛ С ЗАМЕЧАНИЯМИ:
{editor_feedback}

Перепиши оба варианта с учётом всех замечаний — сохрани глубину, исправь отмеченное."""

    result_text = gemini_call(api_key, MODEL, system, user_msg, max_tokens=8000, temperature=0.8)

    if not editor_feedback:
        reflection_text = gemini_call(
            api_key, MODEL, system,
            f"Ты написал тексты для «{topic}». Выдели 1-2 приёма для запоминания.\nФормат: каждый с '•'",
            max_tokens=300, temperature=0.5
        )
        for line in reflection_text.strip().split("\n"):
            if line.strip() and "•" in line:
                memory_utils.add_insight(memory, line.strip().lstrip("•").strip(), topic, "copywriting")

        for fmt_match in re.finditer(r"ВАРИАНТ [АБ]\s*[—-]\s*(.+)", result_text):
            memory_utils.add_used_format(fmt_match.group(1).strip(" *")[:40], topic)

        for cta_match in re.finditer(r"CTA-СЛОВО [АБ]:\**\s*(.+)", result_text):
            cta_text = cta_match.group(1).strip(" *[]")[:60]
            if cta_text and not cta_text.lower().startswith(("без cta", "нет")):
                memory_utils.add_used_cta(cta_text, topic)

    memory_utils.add_topic(memory, topic, f"Итерация {iteration}: {result_text[:200]}")
    memory_utils.save(AGENT_ID, memory)

    return {"agent": "Копирайтер", "topic": topic, "iteration": iteration, "texts": result_text}
